"""
Тема 3. Вейвлеты (PyWavelets). Задание 2. Непрерывное вейвлет-преобразование.

Сигнал x = f(t) задан на [0; 1) с частотой дискретизации sr = 2048.

Что такое непрерывное вейвлет-преобразование W(a, b):
  Берём вейвлет ψ и делаем две вещи:
    * сдвигаем его по времени на b (где смотрим);
    * растягиваем в a раз (a — масштаб: какую «ширину» колебаний ищем).
  В каждом положении считаем «похожесть» сигнала на такой вейвлет:
      W(a, b) = (1/√a) ∫ f(t) ψ((t - b) / a) dt.
  Большое |W| значит, что в момент b в сигнале есть колебание масштаба a.
  Маленький масштаб = сжатый вейвлет = высокая частота,
  большой масштаб = растянутый вейвлет = низкая частота.
  Частота связана с масштабом так: freq = fc / (a * dt),
  где fc — центральная частота вейвлета, dt — шаг дискретизации.

Результат — картинка «время × частота» (скалограмма). В отличие от спектра
Фурье (тема 2), здесь видно, КОГДА в сигнале была каждая частота.

Порождающий вейвлет задаёт преподаватель; по умолчанию 'morl' (Морле).
Его можно поменять переменной WAVELET или вторым аргументом запуска.

Запуск:
  python task2.py            — все 6 вариантов, вейвлет morl
  python task2.py 2          — вариант 2
  python task2.py 2 mexh     — вариант 2, вейвлет «мексиканская шляпа»
"""
import sys
from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
import pywt

RESULTS = Path(__file__).parent / "results"
RESULTS.mkdir(exist_ok=True)

WAVELET = sys.argv[2] if len(sys.argv) > 2 else 'morl'

sr = 2048                 # частота дискретизации
dt = 1.0 / sr             # шаг по времени
t = np.arange(0, 1, dt)

np.random.seed(4321)

# Базовые волны: 1 Гц с амплитудой 1 и 3 Гц с амплитудой 4
wave1 = np.cos(2*np.pi*t)
wave3 = 4*np.cos(6*np.pi*t)

VARIANTS = {
    1: ("cos(2πt) + 4cos(6πt)", wave1 + wave3),
    2: ("cos(2πt) при t<1/2,  4cos(6πt) при t≥1/2", np.where(t < 0.5, wave1, wave3)),
    3: ("4cos(6πt) при t<1/2,  cos(2πt) при t≥1/2", np.where(t < 0.5, wave3, wave1)),
    4: ("cos(2πt) + 4cos(6πt) + равномерный шум [-0.5; 0.5]",
        wave1 + wave3 + np.random.uniform(-0.5, 0.5, len(t))),
    5: ("cos(2πt) + 4cos(6πt) + нормальный шум (0; 0.5)",
        wave1 + wave3 + np.random.normal(0, 0.5, len(t))),
    6: ("exp(t)·(cos(2πt) + 4cos(6πt))", np.exp(t) * (wave1 + wave3)),
}

# Какие частоты хотим «просмотреть»: от 0.5 до 20 Гц (логарифмическая сетка).
# Переводим их в масштабы по формуле a = fc / (freq * dt).
fc = pywt.central_frequency(WAVELET)
target_freqs = np.geomspace(0.5, 20, 120)
scales = fc / (target_freqs * dt)


def process(variant):
    title, x = VARIANTS[variant]
    print(f"=== Вариант {variant}: {title}  (вейвлет {WAVELET})")

    # b) CWT. coef[i, j] = W(a_i, b_j): строка — масштаб (частота), столбец — момент времени.
    # sampling_period=dt позволяет сразу получить частоты freqs в герцах.
    # method='fft' — та же свёртка, но быстрее при больших масштабах.
    coef, freqs = pywt.cwt(x, scales, WAVELET, sampling_period=dt, method='fft')

    # Где в среднем больше всего «энергии» — подсказка, какие частоты главные
    energy = np.mean(np.abs(coef)**2, axis=1)
    print(f"   частота с наибольшей энергией ≈ {freqs[np.argmax(energy)]:.2f} Гц")

    fig, ax = plt.subplots(2, 1, figsize=(11, 8), sharex=True, layout='constrained',
                           gridspec_kw={'height_ratios': [1, 2]})
    fig.suptitle(f"Вариант {variant}: {title}\nвейвлет {WAVELET}")

    # a) График сигнала
    ax[0].plot(t, x, 'r')
    ax[0].set_ylabel('f(t)')
    ax[0].set_title('a) сигнал')

    # c) График |W(a, b)|: по горизонтали время b, по вертикали частота (≈ 1/a).
    # Яркие полосы — частоты, которые присутствуют в сигнале в данный момент.
    im = ax[1].pcolormesh(t, freqs, np.abs(coef), shading='auto', cmap='viridis')
    ax[1].set_yscale('log')
    ax[1].set_yticks([0.5, 1, 2, 3, 5, 10, 20])
    ax[1].set_yticklabels(['0.5', '1', '2', '3', '5', '10', '20'])
    ax[1].set_ylabel('частота, Гц  (≈ 1 / масштаб)')
    ax[1].set_xlabel('время b, с')
    ax[1].set_title('c) |W(a, b)| — непрерывное вейвлет-преобразование')
    # Шкалу цвета привязываем к обоим графикам, чтобы их оси времени совпадали
    fig.colorbar(im, ax=ax, label='|W|')

    ax[1].set_xlim(0, 1)
    fig.savefig(RESULTS / f"task2_variant{variant}_{WAVELET}.png")
    plt.show()


# Что видно на скалограммах:
#   1) две горизонтальные полосы — 1 Гц и 3 Гц — на протяжении всего времени;
#      полоса 3 Гц ярче, потому что её амплитуда 4;
#   2) вторые полсекунды — яркие пятна на 3 Гц (каждое пятно — полуволна
#      косинуса), в первые полсекунды — слабое размытое пятно на низких частотах:
#      за 0.5 с волна 1 Гц успевает сделать лишь пол-колебания, и точно
#      определить её частоту нельзя (чем ниже частота, тем хуже точность по времени);
#   3) то же, но в обратном порядке. В отличие от Фурье, варианты 2 и 3 теперь
#      различимы! От момента скачка (t = 0.5) вверх, к высоким частотам,
#      расходятся линии: скачок содержит сразу все частоты;
#   4, 5) те же полосы, что в 1, плюс мелкая «рябь» на высоких частотах — шум;
#   6) полосы становятся ярче слева направо, потому что exp(t) увеличивает амплитуду.
# У краёв (t ≈ 0 и t ≈ 1) картинка искажается: вейвлет «вылезает» за границы
# сигнала (краевой эффект), особенно на низких частотах, где вейвлет широкий.
if __name__ == "__main__":
    selected = [int(sys.argv[1])] if len(sys.argv) > 1 else list(VARIANTS)
    for v in selected:
        process(v)
