"""
Тема 3. Вейвлеты (PyWavelets). Задание 1.
Обзор семейств вейвлетов: свойства и графики.

Что такое вейвлет (простыми словами):
  «вейвлет» переводится как «маленькая волна». Это короткое колебание,
  которое быстро затухает по краям. Синусоида из преобразования Фурье
  бесконечна, а вейвлет локален, поэтому с его помощью можно понять не только
  КАКАЯ частота есть в сигнале, но и ГДЕ (в какой момент времени) она есть.

Два вида вейвлетов:
  * Дискретные (для DWT): задаются набором коэффициентов фильтра.
    У них две функции:
      φ (phi) — скейлинг-функция («сглаживающая», даёт грубую форму сигнала,
                аппроксимацию);
      ψ (psi) — сам вейвлет («выделяющий детали», даёт перепады и колебания).
  * Непрерывные (для CWT): задаются формулой, скейлинг-функции у них нет.
    Некоторые из них комплексные: у них есть действительная и мнимая часть.

Свойства, которые выводит программа:
  orthogonal     — ортогональный: разложение по нему не содержит «дублей»
                   информации, а обратное преобразование устроено так же
                   просто, как прямое;
  biorthogonal   — биортогональный: для разложения и восстановления
                   используются РАЗНЫЕ (но согласованные) пары функций;
  symmetry       — симметричность формы. Симметричные вейвлеты меньше
                   искажают края объектов на изображениях;
  filter length  — длина фильтра: чем длиннее, тем глаже вейвлет,
                   но тем больше вычислений;
  vanishing moments — число нулевых моментов: вейвлет «не замечает»
                   многочлены степени меньше этого числа, поэтому гладкие
                   участки сигнала дают почти нулевые детали (хорошо для сжатия).

Для каждого семейства из задания выбран один представитель.
"""
from pathlib import Path

import matplotlib.pyplot as plt
import pywt

RESULTS = Path(__file__).parent / "results"
RESULTS.mkdir(exist_ok=True)

# Семейство → выбранный вейвлет
DISCRETE = {
    'Haar': 'haar',
    'Daubechies': 'db4',
    'Symlets': 'sym4',
    'Coiflets': 'coif2',
    'Biorthogonal': 'bior2.2',
    'Reverse biorthogonal': 'rbio2.2',
    'Discrete Meyer (FIR Approximation)': 'dmey',
}
CONTINUOUS = {
    'Gaussian': 'gaus2',
    'Morlet wavelet': 'morl',
    # Шеннон: параметры «ширина полосы - центральная частота»
    'Shannon wavelets': 'shan1.5-1.0',
    # B-сплайн: «порядок - ширина полосы - центральная частота»
    'Frequency B-Spline wavelets': 'fbsp2-1.5-1.0',
}

print("Все семейства в PyWavelets:", pywt.families(short=False))
print("Дискретные вейвлеты:", pywt.wavelist(kind='discrete'))
print("Непрерывные вейвлеты:", pywt.wavelist(kind='continuous'))

# ---------------------------------------------------------------------------
# Дискретные вейвлеты: φ и ψ
# ---------------------------------------------------------------------------
for family, name in DISCRETE.items():
    w = pywt.Wavelet(name)
    print(f"\n=== {family}: {name}")
    print(w)   # полный список свойств
    print("   vanishing moments ψ:", w.vanishing_moments_psi)

    # wavefun строит графики функций приближённо, итеративным способом:
    # level — число шагов уточнения (чем больше, тем глаже кривая).
    res = w.wavefun(level=8)
    fig = plt.figure(figsize=(10, 4))
    if len(res) == 3:
        # Ортогональный вейвлет: одна пара (φ, ψ) и для разложения, и для восстановления
        phi, psi, x = res
        plt.plot(x, phi, 'r', label='φ — скейлинг-функция')
        plt.plot(x, psi, 'g', label='ψ — вейвлет')
    else:
        # Биортогональный: пара для разложения (dec) и пара для восстановления (rec)
        phi_d, psi_d, phi_r, psi_r, x = res
        plt.subplot(1, 2, 1)
        plt.plot(x, phi_d, 'r', label='φ разложения')
        plt.plot(x, psi_d, 'g', label='ψ разложения')
        plt.legend()
        plt.grid(alpha=0.3)
        plt.subplot(1, 2, 2)
        plt.plot(x, phi_r, 'r', label='φ восстановления')
        plt.plot(x, psi_r, 'g', label='ψ восстановления')
    plt.legend()
    plt.grid(alpha=0.3)
    fig.suptitle(f"{family}: {name}")
    fig.tight_layout()
    fig.savefig(RESULTS / f"task1_{name}.png")
    plt.show()

# ---------------------------------------------------------------------------
# Непрерывные вейвлеты: только ψ
# ---------------------------------------------------------------------------
for family, name in CONTINUOUS.items():
    w = pywt.ContinuousWavelet(name)
    print(f"\n=== {family}: {name}")
    print(w)
    # Центральная частота — «основная» частота колебаний вейвлета.
    # Она нужна, чтобы пересчитывать масштаб CWT в частоту в герцах.
    print("   центральная частота:", pywt.central_frequency(name))

    psi, x = w.wavefun(length=1024)
    fig = plt.figure(figsize=(8, 4))
    if w.complex_cwt:
        # Комплексный вейвлет: рисуем действительную и мнимую части.
        # Они похожи на косинус и синус одной частоты, «зажатые» огибающей.
        plt.plot(x, psi.real, 'b', label='Re ψ')
        plt.plot(x, psi.imag, 'm--', label='Im ψ')
    else:
        plt.plot(x, psi, 'g', label='ψ — вейвлет')
    plt.legend()
    plt.grid(alpha=0.3)
    plt.title(f"{family}: {name}")
    fig.tight_layout()
    fig.savefig(RESULTS / f"task1_{name}.png")
    plt.show()

# Краткие выводы по графикам:
#   haar    — «ступенька»: самый простой, разрывный, хорошо ловит скачки;
#   db4     — несимметричный, гладкий, 4 нулевых момента;
#   sym4    — «почти симметричная» версия Добеши с той же гладкостью;
#   coif2   — у скейлинг-функции тоже есть нулевые моменты, форма ещё симметричнее;
#   bior2.2 / rbio2.2 — строго симметричные, пары функций разложения и
#             восстановления у них поменяны местами;
#   dmey    — очень гладкий, но длинный (62 коэффициента фильтра);
#   gaus2   — вторая производная гауссианы (перевёрнутая «мексиканская шляпа»);
#   morl    — косинус внутри гауссова «колокола», удобен для анализа частот;
#   shan, fbsp — комплексные, частотно-локализованные, но медленно затухают по времени.
