"""
Тема 2. Матрицы и массивы (NumPy). Задание 1.

Даны матрицы
        ( 4   1  -2 )              ( -1   3 )
    A = ( 3  -2   5 )  (2x3),  B = (  2  -3 )  (3x2)
                                   (  4   1 )

Программа выполняет пункты a–g: максимумы и минимумы, транспонирование,
сложение и вычитание, поэлементное и матричное умножение,
собственные значения и собственные векторы.
"""
import numpy as np

A = np.array([[4, 1, -2],
              [3, -2, 5]])
B = np.array([[-1, 3],
              [2, -3],
              [4, 1]])

print("A =\n", A)
print("B =\n", B)

# ---------------------------------------------------------------------------
# a) Максимум в каждом столбце A
# ---------------------------------------------------------------------------
# axis=0 означает «идём сверху вниз», то есть вдоль столбца.
# Для каждого из 3 столбцов берём наибольшее из 2 чисел.
print("\na) max по столбцам A:", np.max(A, axis=0))

# ---------------------------------------------------------------------------
# b) Минимум в каждой строке B
# ---------------------------------------------------------------------------
# axis=1 означает «идём слева направо», то есть вдоль строки.
print("b) min по строкам B:", np.min(B, axis=1))

# ---------------------------------------------------------------------------
# c) Транспонирование
# ---------------------------------------------------------------------------
# Строки становятся столбцами: элемент [i, j] переходит на место [j, i].
# A (2x3) превращается в A^T (3x2), B (3x2) превращается в B^T (2x3).
print("\nc) A^T =\n", A.T)
print("   B^T =\n", B.T)

# ---------------------------------------------------------------------------
# d) Сумма A + B^T и разность B - A^T
# ---------------------------------------------------------------------------
# Складывать и вычитать можно только матрицы одинакового размера.
# A и B^T обе 2x3, B и A^T обе 3x2. Операция выполняется поэлементно.
print("\nd) A + B^T =\n", A + B.T)
print("   B - A^T =\n", B - A.T)

# ---------------------------------------------------------------------------
# e) Поэлементное умножение (оператор *)
# ---------------------------------------------------------------------------
# Это НЕ матричное произведение: перемножаются числа, стоящие
# на одинаковых местах: C[i, j] = A[i, j] * B^T[i, j].
print("\ne) A * B^T (поэлементно) =\n", A * B.T)
print("   B * A^T (поэлементно) =\n", B * A.T)

# ---------------------------------------------------------------------------
# f) Матричные произведения (оператор @)
# ---------------------------------------------------------------------------
# Правило «строка на столбец»: элемент [i, j] результата равен сумме
# произведений i-й строки левой матрицы на j-й столбец правой.
# Размеры: (m x k) @ (k x n) -> (m x n); внутренние размеры должны совпадать.
#   A @ B     : (2x3)@(3x2) -> 2x2
#   B @ A     : (3x2)@(2x3) -> 3x3
#   A @ A^T   : (2x3)@(3x2) -> 2x2
#   A^T @ A   : (3x2)@(2x3) -> 3x3
# Видно, что AB ≠ BA: матричное умножение не коммутативно.
products = {
    "AB": A @ B,
    "BA": B @ A,
    "AA^T": A @ A.T,
    "A^TA": A.T @ A,
}
print()
for name, M in products.items():
    print(f"f) {name} =\n", M)

# ---------------------------------------------------------------------------
# g) Собственные значения и собственные векторы
# ---------------------------------------------------------------------------
# Собственный вектор v — это направление, которое матрица M не поворачивает,
# а только растягивает или сжимает:  M v = λ v.
# Число λ — собственное значение (во сколько раз растягивается вектор).
# Находятся из уравнения det(M - λE) = 0.
#
# Интересные факты, которые видны в ответе:
#   * AB (2x2) и BA (3x3) имеют одинаковые ненулевые собственные значения,
#     а у BA добавляется ещё одно, равное 0 (так как ранг BA не больше 2).
#   * AA^T и A^TA — симметричные матрицы, поэтому их собственные значения
#     вещественные и неотрицательные, а собственные векторы перпендикулярны.
#   * Собственные векторы выводятся по столбцам и нормированы (длина = 1).
print()
for name, M in products.items():
    vals, vecs = np.linalg.eig(M)
    print(f"g) {name}: собственные значения =", np.round(vals, 4))
    print("   собственные векторы (по столбцам) =\n", np.round(vecs, 4))
    # Проверка определения M v = λ v для первого вектора
    v, lam = vecs[:, 0], vals[0]
    print("   проверка M v - λ v ≈ 0:", np.allclose(M @ v, lam * v))
    print()
