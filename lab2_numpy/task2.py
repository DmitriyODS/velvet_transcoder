"""
Тема 2. Матрицы и массивы (NumPy). Задание 2. Быстрое преобразование Фурье.

Сигнал x = f(t) задан на [0; 1) с частотой дискретизации sr = 1024,
то есть мы знаем 1024 значения функции через каждые 1/1024 секунды.

Что такое преобразование Фурье (простыми словами):
  любой сигнал можно разложить на сумму синусоид разных частот.
  Преобразование Фурье X(ω) отвечает на вопрос: «какие частоты есть
  в сигнале и с какой амплитудой».
  Обратное преобразование собирает сигнал обратно из этих синусоид.
  БПФ (FFT) — быстрый алгоритм для этого расчёта (N·log N действий вместо N^2).

Что делает программа для каждого варианта f(t):
  a) рисует график f(t);
  b) вычисляет БПФ: X = fft(x);
  c) рисует амплитудный спектр |X(ω)|;
  d) вычисляет обратное БПФ: f1 = ifft(X);
  e) рисует f(t) и f1(t) рядом и сравнивает их.

Запуск:
  python task2.py        — все 6 вариантов
  python task2.py 3      — только вариант 3
"""
import sys
from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
from numpy.fft import fft, ifft

RESULTS = Path(__file__).parent / "results"
RESULTS.mkdir(exist_ok=True)

sr = 1024                 # частота дискретизации: 1024 отсчёта в секунду
ts = 1.0 / sr             # шаг по времени между отсчётами
t = np.arange(0, 1, ts)   # моменты времени 0, 1/1024, 2/1024, ..., 1023/1024

# Фиксируем генератор случайных чисел, чтобы шум был одинаковым при каждом запуске
np.random.seed(4321)

# Две базовые волны:
#   cos(2*pi*t)   — частота 1 Гц (1 колебание за секунду), амплитуда 1;
#   4*cos(6*pi*t) — частота 3 Гц (3 колебания за секунду), амплитуда 4.
wave1 = np.cos(2*np.pi*t)
wave3 = 4*np.cos(6*np.pi*t)

VARIANTS = {
    1: ("cos(2πt) + 4cos(6πt)",
        wave1 + wave3),
    # np.where(условие, A, B): где условие истинно — берём A, иначе B.
    2: ("cos(2πt) при t<1/2,  4cos(6πt) при t≥1/2",
        np.where(t < 0.5, wave1, wave3)),
    3: ("4cos(6πt) при t<1/2,  cos(2πt) при t≥1/2",
        np.where(t < 0.5, wave3, wave1)),
    # Равномерный шум: любое значение из [-0.5; 0.5] равновероятно
    4: ("cos(2πt) + 4cos(6πt) + равномерный шум [-0.5; 0.5]",
        wave1 + wave3 + np.random.uniform(-0.5, 0.5, len(t))),
    # Нормальный (гауссов) шум: чаще всего около 0, разброс σ = 0.5
    5: ("cos(2πt) + 4cos(6πt) + нормальный шум (0; 0.5)",
        wave1 + wave3 + np.random.normal(0, 0.5, len(t))),
    6: ("exp(t)·(cos(2πt) + 4cos(6πt))",
        np.exp(t) * (wave1 + wave3)),
}


def process(variant):
    title, x = VARIANTS[variant]
    print(f"\n=== Вариант {variant}: f(t) = {title}")

    # b) Прямое БПФ.
    # X — массив из N комплексных чисел. Элемент X[k] соответствует частоте k Гц
    # (у нас сигнал длится ровно 1 секунду, поэтому номер k и есть частота).
    # Модуль |X[k]| показывает «силу» частоты k, аргумент — её сдвиг (фазу).
    X = fft(x)
    N = len(X)
    n = np.arange(N)
    T = N / sr            # длительность сигнала в секундах (= 1)
    freq = n / T          # частота, соответствующая каждому X[k]

    # c) Амплитудный спектр.
    # Делим |X| на N/2, чтобы получить амплитуду синусоиды в привычных единицах:
    # для варианта 1 увидим пики высотой 1 на частоте 1 Гц и 4 на частоте 3 Гц.
    # Вторая половина спектра (частоты > sr/2) — зеркальная копия первой,
    # поэтому смотрим только на низкие частоты.
    amplitude = np.abs(X) / (N // 2)
    top = np.argsort(amplitude[:N // 2])[::-1][:3]
    for k in sorted(top):
        if amplitude[k] > 0.05:   # совсем маленькие значения не считаем пиками
                print(f"   пик спектра: частота {freq[k]:.0f} Гц, амплитуда {amplitude[k]:.3f}")

    # d) Обратное БПФ: собираем сигнал из всех частот обратно.
    # Результат комплексный, но мнимая часть — лишь ошибки округления (~1e-16),
    # поэтому берём вещественную часть.
    f1 = ifft(X).real

    # e) Сравнение: разница между f и f1 на уровне ошибок округления,
    # то есть преобразование Фурье не теряет информацию.
    print(f"   max|f - f1| = {np.max(np.abs(x - f1)):.2e}")

    fig, ax = plt.subplots(2, 2, figsize=(12, 8))
    fig.suptitle(f"Вариант {variant}: {title}")

    ax[0, 0].plot(t, x, 'r')
    ax[0, 0].set_title('a) исходный сигнал f(t)')
    ax[0, 0].set_xlabel('t, с')

    ax[0, 1].stem(freq, amplitude, 'b', markerfmt=" ", basefmt="-b")
    ax[0, 1].set_xlim(0, 10)
    ax[0, 1].set_title('c) амплитудный спектр |X(ω)|')
    ax[0, 1].set_xlabel('частота, Гц')

    ax[1, 0].plot(t, x, 'r')
    ax[1, 0].set_title('e) f(t)')
    ax[1, 0].set_xlabel('t, с')

    ax[1, 1].plot(t, f1, 'g')
    ax[1, 1].set_title('e) f1(t) = ifft(X)')
    ax[1, 1].set_xlabel('t, с')

    fig.tight_layout()
    fig.savefig(RESULTS / f"task2_variant{variant}.png")
    plt.show()


# Что будет видно на спектрах:
#   1) два чётких пика: 1 Гц (амплитуда 1) и 3 Гц (амплитуда 4);
#   2, 3) те же частоты, но каждая звучит только полсекунды, поэтому пики
#      ниже (у 3 Гц амплитуда 2 вместо 4) и «расплываются» на соседние частоты
#      (резкий скачок в t = 1/2 требует много частот). Амплитудные спектры
#      вариантов 2 и 3 совпадают полностью: по |X| нельзя понять, КОГДА
#      звучала частота. Эту проблему решают вейвлеты (темы 3–7);
#   4, 5) те же два пика плюс низкий «ковёр» на всех частотах — это шум;
#   6) множитель exp(t) меняет амплитуду со временем, и пики тоже расплываются.
if __name__ == "__main__":
    selected = [int(sys.argv[1])] if len(sys.argv) > 1 else list(VARIANTS)
    for v in selected:
        process(v)
