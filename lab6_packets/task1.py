"""
Тема 6. Вейвлет-пакеты. Задание 1.

Сигнал: x = cos(2πt) + 2cos(6πt), частота дискретизации sr = 16, t ∈ [0; 1)
(всего 16 точек).

Чем вейвлет-пакет отличается от обычного DWT:
  в обычном DWT на каждом уровне дальше раскладывается только аппроксимация
  (a → aa → aaa ...), а детали остаются как есть.
  В вейвлет-пакете раскладываются ОБА узла: и a, и d. Получается полное
  двоичное дерево:
      уровень 0:               (исходный сигнал, 16 чисел)
      уровень 1:          a                 d              (по 8 чисел)
      уровень 2:     aa       ad       da       dd         (по 4 числа)
      уровень 3:  aaa aad  ada add  daa dad  dda ddd       (по 2 числа)
      уровень 4:  16 узлов по 1 числу
  Путь узла читается слева направо: 'ad' — сначала взяли аппроксимацию (a),
  потом у неё детали (d).
  Каждый уровень целиком содержит всю информацию о сигнале: из любого уровня
  можно восстановить исходный сигнал. Узлы уровня — это разбиение частот
  на всё более узкие полосы.

Вейвлет Хаара на одном шаге для пары соседних чисел (x1, x2):
      a = (x1 + x2) / √2,    d = (x1 - x2) / √2.

Сжатие: обнуляем маленькие коэффициенты (|c| < 0.5) и восстанавливаем
сигнал. Смотрим, сколько ненулевых чисел пришлось хранить и какова ошибка
(норма L1 = сумма модулей разностей во всех точках).
"""
from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
import pywt

RESULTS = Path(__file__).parent / "results"
RESULTS.mkdir(exist_ok=True)

sr = 16
t = np.arange(0, 1, 1/sr)
x = np.cos(2*np.pi*t) + 2*np.cos(6*np.pi*t)
THRESHOLD = 0.5
WAVELET = 'haar'

# ---------------------------------------------------------------------------
# m) Разложение в вейвлет-пакет
# ---------------------------------------------------------------------------
wp = pywt.WaveletPacket(data=x, wavelet=WAVELET, mode='symmetric')
# maxlevel = log2(16) = 4: после 4 делений пополам в каждом узле остаётся 1 число
print("Максимальный уровень разложения:", wp.maxlevel)

# ---------------------------------------------------------------------------
# n) Дерево разложения
# ---------------------------------------------------------------------------
fig, ax = plt.subplots(figsize=(16, 6))
for level in range(wp.maxlevel + 1):
    nodes = [wp] if level == 0 else wp.get_level(level, 'natural')
    n = len(nodes)
    for i, node in enumerate(nodes):
        # Узел i уровня level ставим посередине своей «ячейки»
        xpos = (i + 0.5) / n
        ypos = -level
        name = node.path if node.path else 'x'
        ax.text(xpos, ypos, f"{name}\n({len(node.data)})", ha='center', va='center',
                fontsize=9 if level < 4 else 7,
                bbox=dict(boxstyle='round', fc='lightyellow', ec='gray'))
        # Линии к двум потомкам
        if level < wp.maxlevel:
            for child in (2*i, 2*i + 1):
                ax.plot([xpos, (child + 0.5) / (2*n)], [ypos - 0.15, ypos - 0.85],
                        'gray', lw=0.8)
ax.set_xlim(0, 1)
ax.set_ylim(-wp.maxlevel - 0.5, 0.5)
ax.set_yticks(range(0, -wp.maxlevel - 1, -1))
ax.set_yticklabels([f"уровень {k}" for k in range(wp.maxlevel + 1)])
ax.set_xticks([])
ax.set_title("n) Дерево разложения в вейвлет-пакет (в скобках — число коэффициентов)")
fig.tight_layout()
fig.savefig(RESULTS / "task1n_tree.png")
plt.show()

# ---------------------------------------------------------------------------
# o) Обозначения и коэффициенты всех уровней
# ---------------------------------------------------------------------------
np.set_printoptions(precision=4, suppress=True)
print("\no) Все узлы:")
print("   уровень 0: x =", x)
for level in range(1, wp.maxlevel + 1):
    print(f"   --- уровень {level}")
    for node in wp.get_level(level, 'natural'):
        print(f"   {node.path:>5}: {node.data}")


# ---------------------------------------------------------------------------
# Общая функция для пунктов p–s
# ---------------------------------------------------------------------------
def compress_level(level, label):
    """Обнуляет на уровне level коэффициенты с |c| < THRESHOLD и
    восстанавливает сигнал только по узлам этого уровня.

    Создаём пустой пакет и заполняем в нём ТОЛЬКО узлы нужного уровня.
    Метод reconstruct собирает сигнал снизу вверх: из пары (a, d) каждого
    родителя делается обратное преобразование Хаара, и так до корня.
    Узел, коэффициенты которого стали нулями, ничего не добавляет —
    это то же самое, что «удалить лист».
    (Удалять узлы через del в исходном пакете нельзя: если удалить обоих детей,
    PyWavelets возьмёт старые данные родителя, и удаление не сработает.)
    """
    new_wp = pywt.WaveletPacket(data=None, wavelet=WAVELET, mode='symmetric')
    nonzero = 0
    removed = []
    for node in wp.get_level(level, 'natural'):
        c = np.where(np.abs(node.data) < THRESHOLD, 0, node.data)
        if not np.any(c):
            removed.append(node.path)
        nonzero += np.count_nonzero(c)
        new_wp[node.path] = c
    x_rec = new_wp.reconstruct(update=False)[:len(x)]
    l1 = np.sum(np.abs(x - x_rec))

    print(f"\n{label}) уровень {level}: ненулевых коэффициентов {nonzero} из {len(x)}, "
          f"||x - x_rec||_L1 = {l1:.4f}")
    if removed:
        print(f"   полностью обнулены узлы: {removed}")

    plt.figure(figsize=(9, 4))
    plt.plot(t, x, 'r-o', label='исходный')
    plt.plot(t, x_rec, 'g--s', label='восстановленный')
    plt.title(f"{label}) уровень {level}: {nonzero} ненулевых коэф., L1 = {l1:.3f}")
    plt.xlabel('t')
    plt.legend()
    plt.grid(alpha=0.3)
    plt.tight_layout()
    plt.savefig(RESULTS / f"task1{label}_level{level}.png")
    plt.show()
    return nonzero, l1


# p) Листья максимального уровня (4): в каждом листе 1 число
# q) Третий уровень, r) второй уровень, s) первый уровень
res = {}
for label, level in [('p', 4), ('q', 3), ('r', 2), ('s', 1)]:
    res[level] = compress_level(level, label)

# ---------------------------------------------------------------------------
# Выбор лучшего уровня: минимум ненулевых коэффициентов,
# при равенстве — меньшая ошибка
# ---------------------------------------------------------------------------
best = min(res, key=lambda L: (res[L][0], res[L][1]))
print(f"\nЛучший уровень разложения: {best} "
      f"(ненулевых {res[best][0]}, L1 = {res[best][1]:.4f})")

# Как понимать результат:
#     уровень 4: 8 ненулевых, L1 = 0      уровень 3: 14 ненулевых, L1 ≈ 2.27
#     уровень 2: 10 ненулевых, L1 ≈ 2.97  уровень 1: 16 ненулевых, L1 = 0
#   * На каждом уровне ровно 16 чисел (как в сигнале), но распределены они
#     по-разному. Чем глубже уровень, тем уже частотные полосы узлов.
#   * На уровне 4 ровно половина листьев равна нулю — все, чей путь
#     оканчивается на 'a'. Причина: вторая половина сигнала — это первая
#     с обратным знаком, x(t + 1/2) = -x(t) (у частот 1 и 3 Гц за полсекунды
#     проходит нечётное число полупериодов). Последний шаг Хаара складывает
#     «первую половину» со «второй»: a = (c1 + c2)/√2 = (c1 - c1)/√2 = 0.
#     Обнулены только настоящие нули, поэтому сигнал восстанавливается ТОЧНО,
#     а хранить нужно лишь 8 чисел — сжатие в 2 раза.
#   * На уровнях 2 и 3 порог 0.5 обнуляет ненулевые коэффициенты (0.24, 0.28,
#     0.40, 0.47), поэтому появляется ошибка.
#   * На уровне 1 все коэффициенты больше 0.5, обнулять нечего: сжатия нет.
#   * Лучший уровень (наилучший базис для сжатия этого сигнала) — четвёртый:
#     меньше всего ненулевых коэффициентов и нулевая ошибка.
