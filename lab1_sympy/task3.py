"""
Тема 1. Символьные вычисления (SymPy). Задание 3. Ряд Фурье.

Функция: f(t) = t^2 + 2*sin(pi*t) + 4*cos(3*pi*t), отрезок [-4; 4].

Идея ряда Фурье: функцию на отрезке [-L; L] (у нас L = 4) представляют
суммой синусов и косинусов с частотами, кратными базовой:
    r(t) = a0/2 + Σ [ a_n * cos(n*pi*t/L) + b_n * sin(n*pi*t/L) ],  n = 1, 2, 3...
Ряд Тейлора (задание 2) хорошо приближает функцию только около одной точки,
а ряд Фурье приближает её сразу на всём отрезке.

Важная деталь: базовые волны здесь cos(n*pi*t/4), поэтому
  - 2*sin(pi*t)   — это волна с n = 4  (pi*t = 4*pi*t/4),
  - 4*cos(3*pi*t) — это волна с n = 12 (3*pi*t = 12*pi*t/4).
Эти слагаемые уже являются «чистыми» гармониками ряда и попадут в r(t)
только тогда, когда мы возьмём достаточно членов.
Параболу t^2 точно записать конечной суммой волн нельзя,
её приближают многими гармониками cos(n*pi*t/4).

Что делает программа:
  a) раскладывает f(t) в ряд Фурье, берёт 3 члена: r3(t);
  b) рисует f(t) и r3(t) на [-4; 4];
  c) берёт 5 членов: r5(t);
  d) рисует f(t) и r5(t) на [-4; 4].
"""
from pathlib import Path

from sympy import Symbol, sin, cos, pi, fourier_series, plot

RESULTS = Path(__file__).parent / "results"
RESULTS.mkdir(exist_ok=True)

t = Symbol('t')
f = t**2 + 2*sin(pi*t) + 4*cos(3*pi*t)


def compare(f, r, title, filename):
    """Рисует f(t) (синим) и ряд Фурье r(t) (красным) на [-4; 4]."""
    p = plot(f, r, (t, -4, 4), title=title, legend=True, show=False)
    p[0].line_color = 'blue'
    p[0].label = 'f(t)'
    p[1].line_color = 'red'
    p[1].label = 'r(t)'
    p.save(RESULTS / filename)
    p.show()


# fourier_series сам вычисляет интегралы для коэффициентов a_n и b_n.
fs = fourier_series(f, (t, -4, 4))

# ---------------------------------------------------------------------------
# a, b) 3 члена
# ---------------------------------------------------------------------------
# truncate(3) берёт первые 3 НЕНУЛЕВЫХ слагаемых:
#   16/3             — среднее значение функции на отрезке (a0/2);
#   -64 cos(pi t/4)/pi^2, 16 cos(pi t/2)/pi^2 — первые гармоники параболы.
# Получается плавная кривая, которая повторяет только «параболическую» форму
# функции, а быстрых колебаний (n = 4 и n = 12) в ней ещё нет.
r3 = fs.truncate(3)
print("a) r(t) по 3 членам:", r3)
compare(f, r3, 'f и ряд Фурье (3 члена)', 'task3b.png')

# ---------------------------------------------------------------------------
# c, d) 5 членов
# ---------------------------------------------------------------------------
# Добавляются гармоники n = 3 и n = 4. При n = 4 в ряд входит 2 sin(pi t),
# причём ровно с коэффициентом 2: SymPy «нашёл» это слагаемое функции целиком.
# Быстрый 4 cos(3pi t) (n = 12) по-прежнему не попадает, поэтому
# r5(t) проходит «посередине» между колебаниями f(t).
r5 = fs.truncate(5)
print("c) r(t) по 5 членам:", r5)
compare(f, r5, 'f и ряд Фурье (5 членов)', 'task3d.png')
