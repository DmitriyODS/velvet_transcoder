"""
Тема 1. Символьные вычисления (SymPy). Задание 1.

Функция: f(t) = t^2 + 2*sin(pi*t) + 4*cos(3*pi*t)

Что делает программа:
  a) строит график f(t) на отрезке [-4; 4];
  b) находит производную f'(t) в общем виде (формулой);
  c) подставляет t = 2 в производную;
  d) находит неопределённый интеграл (первообразную);
  e) вычисляет определённый интеграл от -4 до 4 двумя способами:
     точно (формулой) и численно (приближённо).

SymPy отличается от обычного Python тем, что работает с формулами,
а не с числами: он хранит pi как символ pi, а не как 3.14159...
Поэтому ответы получаются точными, как на бумаге.
"""
from pathlib import Path

from sympy import Symbol, sin, cos, pi, diff, integrate, Integral, plot, simplify

RESULTS = Path(__file__).parent / "results"
RESULTS.mkdir(exist_ok=True)

# Объявляем t символьной переменной: теперь t — это буква,
# а не число, и с ней можно выполнять алгебраические преобразования.
t = Symbol('t')
f = t**2 + 2*sin(pi*t) + 4*cos(3*pi*t)
print("f(t) =", f)

# ---------------------------------------------------------------------------
# a) График функции на [-4; 4]
# ---------------------------------------------------------------------------
# t^2 — парабола (задаёт общий подъём по краям),
# 2*sin(pi*t) — медленная волна с периодом 2,
# 4*cos(3*pi*t) — быстрая волна с периодом 2/3 и большой амплитудой 4.
# На графике видна «дрожащая» парабола.
p = plot(f, (t, -4, 4), title='f(t) на [-4; 4]', show=False)
p.save(RESULTS / 'task1a_f.png')
p.show()

# ---------------------------------------------------------------------------
# b) Производная f'(t)
# ---------------------------------------------------------------------------
# Производная показывает скорость изменения функции.
# Правила, которые применяет diff:
#   (t^2)'          = 2t
#   (2 sin(pi t))'  = 2 * pi * cos(pi t)       (производная сложной функции:
#                                               множитель pi «выходит» наружу)
#   (4 cos(3 pi t))' = -4 * 3pi * sin(3 pi t) = -12 pi sin(3 pi t)
df = diff(f, t)
print("\nb) f'(t) =", df)

# ---------------------------------------------------------------------------
# c) Значение производной в точке t = 2
# ---------------------------------------------------------------------------
# Подставляем t = 2: cos(2pi) = 1, sin(6pi) = 0, поэтому
# f'(2) = 2*2 + 2pi*1 - 12pi*0 = 4 + 2pi.
df_at_2 = df.subs(t, 2)
print("c) f'(2) =", df_at_2, "≈", df_at_2.evalf())

# ---------------------------------------------------------------------------
# d) Неопределённый интеграл (первообразная)
# ---------------------------------------------------------------------------
# Ищем функцию F(t), у которой производная равна f(t):
#   ∫ t^2 dt          = t^3 / 3
#   ∫ 2 sin(pi t) dt  = -2 cos(pi t) / pi
#   ∫ 4 cos(3pi t) dt = 4 sin(3pi t) / (3pi)
# (SymPy не пишет «+ C», но константа подразумевается.)
F = integrate(f, t)
print("\nd) ∫ f(t) dt =", F, "+ C")
# Проверка: производная первообразной должна вернуть исходную функцию.
print("   проверка F'(t) - f(t) =", simplify(diff(F, t) - f))

# ---------------------------------------------------------------------------
# e) Определённый интеграл от -4 до 4
# ---------------------------------------------------------------------------
# Геометрически это площадь под графиком (с учётом знака).
# Точный способ: формула Ньютона–Лейбница F(4) - F(-4).
#   - синус — нечётная функция, на симметричном отрезке [-4; 4]
#     его площади слева и справа взаимно уничтожаются → 0;
#   - cos(3pi t) на [-4; 4] укладывается целым числом периодов → 0;
#   - остаётся только ∫ t^2 = (64 - (-64)) / 3 = 128/3.
exact = integrate(f, (t, -4, 4))
print("\ne) точно:   ∫_{-4}^{4} f(t) dt =", exact, "=", exact.evalf())

# Численный способ: Integral(...) — «неразвёрнутый» интеграл.
# Метод evalf() не ищет первообразную, а считает площадь приближённо:
# разбивает отрезок на кусочки и складывает их площади (квадратурная формула).
numeric = Integral(f, (t, -4, 4)).evalf()
print("   численно: ∫_{-4}^{4} f(t) dt ≈", numeric)
