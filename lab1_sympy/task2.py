"""
Тема 1. Символьные вычисления (SymPy). Задание 2. Степенной ряд (ряд Тейлора).

Функция: f(t) = t^2 + 2*sin(pi*t) + 4*cos(3*pi*t)

Идея степенного ряда: вблизи точки t = 0 любую «гладкую» функцию можно
приблизить многочленом
    s(t) = c0 + c1*t + c2*t^2 + c3*t^3 + ...
где коэффициенты берутся из производных: c_k = f^(k)(0) / k!.
Чем больше членов, тем лучше приближение и тем дальше от нуля оно работает.
Но многочлен при больших |t| всё равно «улетает» в бесконечность,
а f(t) колеблется, поэтому вдали от нуля приближение плохое.

Что делает программа:
  a) раскладывает f(t) в ряд по 3 членам: s3(t);
  b, c, d) сравнивает f(t) и s3(t) на отрезках [-0.5; 0.5], [-1; 1], [-4; 4];
  e) раскладывает в ряд по 5 членам: s5(t);
  f) сравнивает f(t) и s5(t) на [-1; 1].
"""
from pathlib import Path

from sympy import Symbol, sin, cos, pi, series, plot

RESULTS = Path(__file__).parent / "results"
RESULTS.mkdir(exist_ok=True)

t = Symbol('t')
f = t**2 + 2*sin(pi*t) + 4*cos(3*pi*t)


def compare(f, s, a, b, title, filename):
    """Рисует f(t) (синим) и приближение s(t) (красным) на отрезке [a; b]."""
    p = plot(f, s, (t, a, b), title=title, legend=True, show=False)
    p[0].line_color = 'blue'
    p[0].label = 'f(t)'
    p[1].line_color = 'red'
    p[1].label = 's(t)'
    p.save(RESULTS / filename)
    p.show()


# ---------------------------------------------------------------------------
# a) Ряд из 3 членов
# ---------------------------------------------------------------------------
# series(f, t, 0, 3) даёт многочлен до t^2 включительно плюс «хвост» O(t^3).
# Откуда берутся коэффициенты (разложения известных функций):
#   sin(x) = x - x^3/6 + ...       → 2 sin(pi t) = 2pi t - pi^3 t^3/3 + ...
#   cos(x) = 1 - x^2/2 + x^4/24 - ... → 4 cos(3pi t) = 4 - 18pi^2 t^2 + 27pi^4 t^4/2 - ...
# Складываем с t^2 и группируем по степеням t.
# removeO() убирает символ O(t^3), чтобы получился обычный многочлен.
s3 = series(f, t, 0, 3).removeO()
print("a) s(t) по 3 членам:", s3)

# ---------------------------------------------------------------------------
# b, c, d) Сравнение на всё более широких отрезках
# ---------------------------------------------------------------------------
# Рядом с нулём (|t| < 0.1) графики почти совпадают.
# Уже на [-0.5; 0.5] парабола s3(t) расходится с колебаниями f(t),
# а на [-4; 4] разница огромная: многочлен 2-й степени не может
# повторить много колебаний косинуса.
compare(f, s3, -0.5, 0.5, 'f и s (3 члена), [-0.5; 0.5]', 'task2b.png')
compare(f, s3, -1, 1, 'f и s (3 члена), [-1; 1]', 'task2c.png')
compare(f, s3, -4, 4, 'f и s (3 члена), [-4; 4]', 'task2d.png')

# ---------------------------------------------------------------------------
# e) Ряд из 5 членов
# ---------------------------------------------------------------------------
# Добавляются слагаемые с t^3 и t^4. Приближение становится точнее
# около нуля, но на [-1; 1] всё равно заметно расходится с f(t):
# у cos(3pi t) частота высокая, и для него нужно гораздо больше членов.
s5 = series(f, t, 0, 5).removeO()
print("e) s(t) по 5 членам:", s5)

# ---------------------------------------------------------------------------
# f) Сравнение на [-1; 1]
# ---------------------------------------------------------------------------
compare(f, s5, -1, 1, 'f и s (5 членов), [-1; 1]', 'task2f.png')
