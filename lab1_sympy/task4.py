"""
Тема 1. Символьные вычисления (SymPy). Задание 4.
Коэффициенты Фурье a_n и b_n в аналитическом виде.

Функция: f(t) = t^2 + 2*sin(pi*t) + 4*cos(3*pi*t), отрезок [-L; L], L = 4.

Формулы коэффициентов:
    a_n = (1/L) * ∫_{-L}^{L} f(t) * cos(n*pi*t/L) dt
    b_n = (1/L) * ∫_{-L}^{L} f(t) * sin(n*pi*t/L) dt
Смысл: умножаем функцию на «эталонную» волну и усредняем.
Если в функции есть такая волна, интеграл получится ненулевым
(это «мера похожести» функции на волну частоты n).

Интеграл считается по каждому слагаемому f(t) отдельно, так нагляднее.
После интегрирования в ответе появляются sin(pi*n) и cos(pi*n).
Так как n — целое число, по заданию подставляем
    sin(pi*n) = 0,   cos(pi*n) = (-1)^n
и упрощаем командой simplify.
"""
from sympy import Symbol, sin, cos, pi, integrate, simplify

t = Symbol('t')
# n объявлен просто положительным, без признака «целое»,
# иначе SymPy сам сразу подставит sin(pi*n) = 0 и мы не увидим этот шаг.
n = Symbol('n', positive=True)
L = 4

terms = {
    't^2': t**2,
    '2 sin(pi t)': 2*sin(pi*t),
    '4 cos(3 pi t)': 4*cos(3*pi*t),
}

# Правило замены для целого n
integer_rules = {sin(pi*n): 0, cos(pi*n): (-1)**n}

a_total = 0
b_total = 0
for name, g in terms.items():
    a_raw = integrate(g*cos(n*pi*t/L), (t, -L, L)) / L
    b_raw = integrate(g*sin(n*pi*t/L), (t, -L, L)) / L
    a_n = simplify(a_raw.subs(integer_rules))
    b_n = simplify(b_raw.subs(integer_rules))
    a_total += a_n
    b_total += b_n
    print(f"Слагаемое {name}:")
    print("   a_n до подстановки:", a_raw)
    print("   a_n =", a_n)
    print("   b_n =", b_n)
    print()

# Свободный член a_0 считается отдельно (при n = 0 формула выше делит на ноль).
# a_0/2 — это среднее значение функции на отрезке.
a0 = integrate(t**2 + 2*sin(pi*t) + 4*cos(3*pi*t), (t, -L, L)) / L
print("a_0 =", a0, "  (a_0/2 =", a0/2, "— среднее значение f)")
print()

# Пояснение результата:
#   t^2 — чётная функция, поэтому синусов в ней нет (b_n = 0),
#        а косинусные коэффициенты равны 64*(-1)^n / (pi^2 n^2):
#        они убывают как 1/n^2, т.е. высокие гармоники вносят всё меньший вклад.
#   2 sin(pi t) — сама является гармоникой n = 4, поэтому
#        b_4 = 2, а при остальных n интеграл равен нулю
#        (синусы и косинусы разных частот «ортогональны»: их произведение
#        в среднем равно нулю).
#   4 cos(3pi t) — это гармоника n = 12, поэтому a_12 получает добавку 4.
print("Итог:")
print("   a_n =", a_total)
print("   b_n =", b_total)
