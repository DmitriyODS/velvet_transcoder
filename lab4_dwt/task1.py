"""
Тема 4. Дискретное вейвлет-преобразование (DWT). Задание 1.
Одноуровневое разложение, обнуление деталей, восстановление.

Как работает один уровень DWT (простыми словами):
  Сигнал пропускают через два фильтра:
    * низкочастотный (сглаживающий) — получаются АППРОКСИМИРУЮЩИЕ
      коэффициенты cA: «грубая», плавная форма сигнала;
    * высокочастотный (выделяющий перепады) — получаются ДЕТАЛИЗИРУЮЩИЕ
      коэффициенты cD: мелкие быстрые колебания и шум.
  После каждого фильтра берут каждый второй отсчёт, поэтому
  cA и cD вместе имеют примерно столько же чисел, сколько исходный сигнал.
  Для вейвлета Хаара это совсем просто: для каждой пары соседних точек
      cA = (x1 + x2) / √2   (среднее, умноженное на √2),
      cD = (x1 - x2) / √2   (разность).

Если обнулить cD и восстановить сигнал, останется только сглаженная версия.
Если детали были малы (гладкий сигнал), потеря небольшая, хотя мы
выбросили половину коэффициентов. На этом основано сжатие.
Если детали — это в основном шум, то обнуление cD ещё и очищает сигнал.

Сигналы заданы на [0; 4) по 1024 точкам:
  a) cos(2πt) + 4cos(6πt) + r(t),  r — равномерный шум на [-0.5; 0.5]
  b) 4t - t^2 + r(t),              r — нормальный шум (0; 0.5)
  c) t + exp(0.3t)·4cos(6πt)
Вейвлеты: haar, db4, dmey, bior2.2, rbio2.2, sym4.
"""
from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
import pywt

RESULTS = Path(__file__).parent / "results"
RESULTS.mkdir(exist_ok=True)

np.random.seed(4321)

N = 1024
t = np.linspace(0, 4, N, endpoint=False)   # 1024 точки на [0; 4), шаг 4/1024

# Для каждого сигнала храним и «чистую» часть без шума — чтобы дополнительно
# посмотреть, насколько восстановленный сигнал близок к истинной функции.
clean_a = np.cos(2*np.pi*t) + 4*np.cos(6*np.pi*t)
clean_b = 4*t - t**2
clean_c = t + np.exp(0.3*t) * 4*np.cos(6*np.pi*t)

SIGNALS = {
    'a': ("cos(2πt) + 4cos(6πt) + равномерный шум",
          clean_a + np.random.uniform(-0.5, 0.5, N), clean_a),
    'b': ("4t - t² + нормальный шум",
          clean_b + np.random.normal(0, 0.5, N), clean_b),
    'c': ("t + exp(0.3t)·4cos(6πt)",
          clean_c, clean_c),
}

WAVELETS = ['haar', 'db4', 'dmey', 'bior2.2', 'rbio2.2', 'sym4']

summary = {}
for key, (title, x, clean) in SIGNALS.items():
    print(f"\n=== Сигнал {key}: {title}")
    # Дополнительно считаем СКО (среднеквадратичное отклонение) от чистой
    # функции: до обработки это просто уровень шума, после — остаток шума.
    rms_before = np.sqrt(np.mean((x - clean)**2))
    print(f"   СКО от чистой функции до обработки: {rms_before:.4f}")
    print(f"{'вейвлет':>9} | {'max|x - x_rec|':>15} | {'СКО от чистой после':>20}")

    fig, axes = plt.subplots(2, 3, figsize=(15, 7), sharex=True, sharey=True)
    fig.suptitle(f"Сигнал {key}: {title}. Одноуровневое DWT, детали обнулены")
    errors = {}

    for ax, wname in zip(axes.flat, WAVELETS):
        # Разложение на один уровень: cA — аппроксимация, cD — детали
        cA, cD = pywt.dwt(x, wname)

        # Обнуляем все детализирующие коэффициенты
        cD_zero = np.zeros_like(cD)

        # Обратное преобразование тем же вейвлетом.
        # Срезаем [:N], потому что у длинных фильтров длина может отличаться на 1.
        x_rec = pywt.idwt(cA, cD_zero, wname)[:N]

        # Максимальная погрешность — наибольшее отклонение в какой-нибудь точке
        err = np.max(np.abs(x - x_rec))
        rms_after = np.sqrt(np.mean((x_rec - clean)**2))
        errors[wname] = err
        print(f"{wname:>9} | {err:15.4f} | {rms_after:20.4f}")

        ax.plot(t, x, 'r', lw=0.8, label='исходный')
        ax.plot(t, x_rec, 'g', lw=1.2, label='восстановленный')
        ax.set_title(f"{wname}: max погрешность = {err:.3f}")
        ax.legend(loc='upper right', fontsize=8)

    fig.tight_layout()
    fig.savefig(RESULTS / f"task1_signal_{key}.png")
    plt.show()

    best = min(errors, key=errors.get)
    summary[key] = best
    print(f"   лучший вейвлет для сигнала {key}: {best}")

print("\nИтог (минимальная максимальная погрешность):")
for key, best in summary.items():
    print(f"   сигнал {key}: {best}")

# Как понимать результат:
#   * В сигналах a и b максимальная погрешность примерно равна амплитуде шума:
#     почти всё, что мы «потеряли», — это шум. Шум состоит из самых высоких
#     частот, поэтому он попадает в cD.
#   * Об этом же говорит СКО от чистой функции: после обнуления деталей оно
#     уменьшается примерно в √2 раз (для a: 0.285 → 0.20, для b: 0.50 → 0.36).
#     Белый шум делится между cA и cD поровну, и мы выбросили его половину.
#     Обнуление деталей работает как простой фильтр шума.
#   * В сигналах с шумом разница между вейвлетами небольшая и зависит от
#     конкретной реализации шума.
#   * У сигнала c шума нет, и функция гладкая, поэтому детали очень малы.
#     Лучший вейвлет — db4 (погрешность ~0.001): у него 4 нулевых момента,
#     и гладкие участки дают почти нулевые детали. Хуже всех haar (~0.48):
#     он приближает сигнал «ступеньками» и плохо описывает плавные кривые.
#   * Итог: для всех трёх сигналов лучший вейвлет — db4, для гладкого сигнала
#     он заметно лучше остальных.
