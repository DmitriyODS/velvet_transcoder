"""
Тема 4. Дискретное вейвлет-преобразование (DWT). Задание 2.
Многоуровневое разложение и сжатие (оставляем 10% коэффициентов).

Сигнал на [0; 4), частота дискретизации 1024 (всего 4096 точек):
    f1(t) = t^2 + sin(2πt)                     на [0; 2)
    f2(t) = 4 - t + exp(-0.2t)·sin(4πt)        на [2; 4)
В точке t = 2 функция скачком меняется с 4 на 2.

Многоуровневое разложение (wavedec):
  на первом уровне сигнал делится на cA1 (грубая форма) и cD1 (мелкие детали);
  затем cA1 снова делится на cA2 и cD2, и так далее.
  После L уровней получаем набор [cA_L, cD_L, ..., cD2, cD1]:
    cD1 — самые мелкие и быстрые детали (длина ≈ N/2),
    cD2 — детали покрупнее (≈ N/4),
    ...
    cA_L — очень сглаженный «скелет» сигнала (≈ N/2^L).
  Каждый уровень — это «взгляд на сигнал с увеличением» в 2 раза меньше.

Сжатие: у гладкого сигнала почти вся информация сосредоточена в немногих
больших коэффициентах, а большинство остальных близки к нулю.
Оставляем 10% самых больших по модулю, остальные обнуляем:
чисел нужно хранить в 10 раз меньше, а сигнал восстанавливается почти точно.

Программа выполняет пункты a–l для вейвлетов db4, bior2.2, sym4
и числа уровней 3, 5, 10.
"""
from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
import pywt

RESULTS = Path(__file__).parent / "results"
RESULTS.mkdir(exist_ok=True)

sr = 1024
t = np.arange(0, 4, 1/sr)          # 4096 точек

# np.where выбирает формулу f1 или f2 в зависимости от t
x = np.where(t < 2,
             t**2 + np.sin(2*np.pi*t),
             4 - t + np.exp(-0.2*t) * np.sin(4*np.pi*t))

KEEP = 0.10                        # доля сохраняемых коэффициентов
WAVELETS = ['db4', 'bior2.2', 'sym4']
LEVELS = [3, 5, 10]


def compress(coeffs, keep):
    """Оставляет долю keep самых больших по модулю коэффициентов, остальные = 0.

    Порог выбирается общий для всех уровней: собираем все коэффициенты
    в один массив, находим такое число, что больше него по модулю ровно
    keep·100% коэффициентов (квантиль), и обнуляем всё, что меньше.
    """
    flat = np.concatenate([np.abs(c) for c in coeffs])
    threshold = np.quantile(flat, 1 - keep)
    new = [np.where(np.abs(c) >= threshold, c, 0) for c in coeffs]
    kept = sum(np.count_nonzero(c) for c in new)
    return new, kept, len(flat)


results = {}
for wname in WAVELETS:
    for level in LEVELS:
        # Максимально «честное» число уровней: после него длина фильтра
        # становится больше длины коэффициентов. Если просим больше
        # (level = 10), PyWavelets предупредит: на последних уровнях
        # коэффициенты почти целиком состоят из краевых эффектов.
        max_level = pywt.dwt_max_level(len(x), pywt.Wavelet(wname).dec_len)

        # b) Разложение
        coeffs = pywt.wavedec(x, wname, level=level)
        names = [f'cA{level}'] + [f'cD{level - i}' for i in range(level)]

        # d) Оставляем 10% наибольших коэффициентов
        coeffs_c, kept, total = compress(coeffs, KEEP)

        # e) Восстанавливаем сигнал
        x_rec = pywt.waverec(coeffs_c, wname)[:len(x)]

        # f) Суммарная погрешность по всем точкам: Σ |x_i - x_rec_i|
        total_err = np.sum(np.abs(x - x_rec))
        results[(wname, level)] = total_err
        print(f"{wname:>8}, уровней {level:2d} (макс. рекомендуемый {max_level}): "
              f"оставлено {kept} из {total} коэф., суммарная погрешность = {total_err:.3f}")

        # c) Графики коэффициентов (слева) и g) исходный/восстановленный сигнал (справа)
        n = len(coeffs)
        fig = plt.figure(figsize=(15, max(6, 1.1*n)))
        fig.suptitle(f"{wname}, {level} уровней: коэффициенты и восстановление по {int(KEEP*100)}%")
        for i, (c, name) in enumerate(zip(coeffs, names)):
            ax = fig.add_subplot(n, 2, 2*i + 1)
            ax.plot(c, lw=0.8)
            ax.set_ylabel(name, rotation=0, labelpad=20)
            ax.tick_params(labelsize=7)
        ax = fig.add_subplot(1, 2, 2)
        ax.plot(t, x, 'r', label='исходный')
        ax.plot(t, x_rec, 'g--', label='восстановленный')
        ax.set_title(f"суммарная погрешность = {total_err:.3f}")
        ax.set_xlabel('t')
        ax.legend()
        fig.tight_layout()
        fig.savefig(RESULTS / f"task2_{wname}_level{level}.png")
        plt.show()

# ---------------------------------------------------------------------------
# l) Анализ
# ---------------------------------------------------------------------------
print("\nСуммарная погрешность (строки — вейвлет, столбцы — число уровней):")
print(f"{'':>8} " + " ".join(f"{L:>9}" for L in LEVELS))
for wname in WAVELETS:
    print(f"{wname:>8} " + " ".join(f"{results[(wname, L)]:9.3f}" for L in LEVELS))
best = min(results, key=results.get)
print(f"\nЛучший вариант: {best[0]}, {best[1]} уровней")

# Как понимать результат:
#   * 3 уровня — огромная погрешность (~167 для всех вейвлетов). Причина в
#     длине cA3: это ≈ 1/8 всех коэффициентов (≈ 516 чисел), и все они большие,
#     потому что в них хранится форма сигнала. Бюджет 10% (≈ 412 чисел) меньше
#     длины cA3, поэтому обнуляется даже часть «скелета» сигнала.
#   * 5 уровней — погрешность почти нулевая. cA5 — это ≈ 1/32 коэффициентов
#     (≈ 134 числа), и после него остаётся бюджет на важные детали: скачок
#     в t = 2 и синусоиды. Остальные ~90% деталей и так близки к нулю.
#   * 10 уровней — больше рекомендуемого максимума (9). Последние уровни
#     состоят из нескольких чисел, искажённых краевыми эффектами, поэтому
#     результат чуть хуже, чем при 5 уровнях.
#   * db4 и sym4 дают одинаковый результат: у обоих 4 нулевых момента
#     (sym4 — это «симметризованный» db4). У bior2.2 всего 2 нулевых момента,
#     поэтому парабола t² даёт больше заметных деталей и погрешность больше.
#   * Вывод: лучше всего db4 или sym4 при 5 уровнях. Слишком мало уровней
#     плохо для сжатия, слишком много ничего не даёт.
